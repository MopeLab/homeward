"""Create the river geometry and a seamlessly repeating night-water texture."""
from pathlib import Path
import hashlib
import base64
import io
import json
import math
import struct

import numpy as np
from PIL import Image


OUT = Path(__file__).resolve().parent
SIZE = 1024
EXTENT = 2048.0
HEIGHT = -.38
CENTER_Z = 13.0
SCALE_X, SCALE_Z = 19.0, 18.0
TILE_METRES = 4.8


def metre(uv, scale):
    return scale * np.tan((uv * 2 - 1) * math.atan(EXTENT / scale))


def make_surface_texture():
    # Integer wave vectors and periodic domain warping keep all four edges seamless.
    angle = (np.arange(SIZE, dtype=np.float32) + .5) * (2 * np.pi / SIZE)
    x, z = angle[None, :], angle[:, None]
    u = x + .10*np.sin(2*z+x) + .07*np.sin(3*x-z)
    v = z + .09*np.sin(2*x-z) + .055*np.cos(2*z+x)
    swell = .45*np.sin(2*u+4*v) + .32*np.cos(5*u-3*v) + .23*np.sin(3*u+7*v)
    crests = np.zeros_like(swell)
    for kx,kz,phase,weight in ((3,14,.8,.34),(-5,19,2.8,.30),(7,22,1.3,.21),(-13,27,4.9,.15)):
        ridge = .5+.5*np.cos(kx*u+kz*v+phase+1.5*np.sin(3*u+v))
        crests += weight*ridge**5
    breaks = (.5+.5*np.sin(3*u-4*v))*(.5+.5*np.cos(2*v+u))
    tone = 4.0*swell + (10+19*breaks)*(crests-.18)
    rgb = np.array([41,67,74]) + tone[:,:,None]*np.array([.85,1.05,1.09])
    img = Image.fromarray(np.uint8(np.rint(np.clip(rgb,0,255))))
    buf = io.BytesIO()
    img.save(buf,format="PNG",compress_level=8)
    return buf.getvalue()


def align(data, padding=b'\0'):
    return data + padding*((-len(data))%4)


def write_display_texture(png):
    # Keep one byte of palette index per pixel in the Lua source. The engine's
    # normal GLB path compresses dark colours in 4x4 blocks on desktop.
    alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    palette=np.clip(np.rint(np.array([41,67,74])+
        (np.arange(64)[:,None]-28)*np.array([.85,1.05,1.09])),0,255).astype(np.uint8)
    mip=Image.open(io.BytesIO(png)).resize((512,512),Image.Resampling.LANCZOS)
    levels=[]
    while True:
        tone=(np.asarray(mip)[:,:,1].astype(float)-67)/1.05
        indices=np.clip(np.rint(tone+28),0,63).astype(np.uint8)
        levels.append(np.frombuffer(alphabet.encode(),dtype=np.uint8)[indices].tobytes().decode())
        if mip.width==1: break
        mip=mip.resize((mip.width//2,mip.height//2),Image.Resampling.BOX)
    lut="".join(base64.b64encode(row.tobytes()).decode() for row in palette)
    script="""-- Generated by build_river.py. RGB24 plus all ten mip levels.
function MakeRiverDisplayTexture()
    local U=CS.UnityEngine
    local alphabet='ALPHABET'
    local palette='PALETTE'
    local lut={}
    for i=1,#alphabet do lut[alphabet:sub(i,i)]=palette:sub(4*i-3,4*i) end
    local levels='LEVELS'
    local packed=levels:gsub(".",lut)
    local bytes=CS.System.Convert.FromBase64String(packed)
    local tex=U.Texture2D(512,512,U.TextureFormat.RGB24,true)
    tex:LoadRawTextureData(bytes)
    tex:Apply(false,true)
    tex.name="River fine colour"
    return tex
end
"""
    (OUT/"river-display.lua").write_text(script.replace("ALPHABET",alphabet).replace(
        "PALETTE",lut).replace("LEVELS","".join(levels)),encoding="utf-8")


def export():
    # Retain the tested collider and waterline. All positions are exactly
    # coplanar and share an upward normal, with no side or underside triangles.
    axis=np.linspace(0,1,129,dtype=np.float64)
    u,v=np.meshgrid(axis,axis)
    x=metre(u,SCALE_X)
    z=metre(v,SCALE_Z)+CENTER_Z
    # Existing importer mirrors glTF X when placing models in Unity.
    pos=np.stack([-x,np.full_like(x,HEIGHT),z],axis=-1).astype('<f4').reshape(-1,3)
    tex=np.stack([x/TILE_METRES,z/TILE_METRES],axis=-1).astype('<f4').reshape(-1,2)
    norm=np.tile([0,1,0],(len(pos),1)).astype('<f4')
    a=np.flatnonzero((u<1)&(v<1)).astype(np.uint16)
    b=a+1;c=a+len(axis);d=c+1
    indices=np.stack([a,b,c,b,d,c],axis=-1).astype('<u2').ravel()
    image=make_surface_texture()
    write_display_texture(image)
    data=bytearray();views=[]
    for array,target in [(pos,34962),(norm,34962),(tex,34962),(indices,34963),(image,None)]:
        raw=array if isinstance(array,bytes) else array.tobytes()
        view={"buffer":0,"byteOffset":len(data),"byteLength":len(raw)}
        if target: view["target"]=target
        views.append(view);data.extend(align(raw))
    accessors=[
        {"bufferView":0,"componentType":5126,"count":len(pos),"type":"VEC3","min":pos.min(0).tolist(),"max":pos.max(0).tolist()},
        {"bufferView":1,"componentType":5126,"count":len(pos),"type":"VEC3"},
        {"bufferView":2,"componentType":5126,"count":len(pos),"type":"VEC2"},
        {"bufferView":3,"componentType":5123,"count":len(indices),"type":"SCALAR"}]
    doc={"asset":{"version":"2.0","generator":"Homeward river surface"},"scene":0,
         "scenes":[{"nodes":[0]}],"nodes":[{"mesh":0,"name":"RainRiverSurface"}],
         "meshes":[{"name":"RainRiverSurface","primitives":[{"attributes":{"POSITION":0,"NORMAL":1,"TEXCOORD_0":2},"indices":3,"material":0}]}],
         "materials":[{"name":"RainRiverWater","pbrMetallicRoughness":{"baseColorTexture":{"index":0},"metallicFactor":0,"roughnessFactor":.94}}],
         "textures":[{"sampler":0,"source":0}],"samplers":[{"magFilter":9729,"minFilter":9987,"wrapS":10497,"wrapT":10497}],
         "images":[{"mimeType":"image/png","bufferView":4,"name":"Fine cross-river capillary waves"}],"buffers":[{"byteLength":len(data)}],
         "bufferViews":views,"accessors":accessors}
    js=align(json.dumps(doc,separators=(',',':')).encode(),b' ')
    glb=(struct.pack('<4sII',b'glTF',2,28+len(js)+len(data))+struct.pack('<I4s',len(js),b'JSON')+js+
         struct.pack('<I4s',len(data),b'BIN\0')+data)
    (OUT/'river-surface.glb').write_bytes(glb)
    print(len(glb),'bytes, sha256',hashlib.sha256(glb).hexdigest())


if __name__=='__main__': export()
